"""Independent native64 Host Program ABI (minimal closed loop).

This minimal teaching/probe contract is independent from the production HostContractSpec renderer.
The C compiler owns structure layout and all addresses are obtained through generated accessors.
Production integration uses ``native_abi.py``/``native_runtime.py`` instead of this minimal probe.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import subprocess
from typing import Iterable

from .errors import HostProgramError


@dataclass(frozen=True)
class NativeField:
    name: str
    ctype: str
    numel: int
    elem_nbytes: int


@dataclass(frozen=True)
class NativeContract:
    name: str
    shape_fields: tuple[NativeField, ...]
    inputs: tuple[NativeField, ...]
    workspaces: tuple[NativeField, ...]

    def header(self) -> str:
        lines = [
            "/* Generated by ShapeForge native_contract.py; native64 only. */",
            "#ifndef SF_NATIVE_CONTRACT_H",
            "#define SF_NATIVE_CONTRACT_H",
            "#include <stdint.h>",
            "#include <stddef.h>",
            "",
            "#define SF_NATIVE_ABI_VERSION 1u",
            "#define SF_NATIVE_MAX_INPUTS 64u",
            "#define SF_NATIVE_MAX_WORKSPACES 16u",
            "",
        ]
        for name, fields in (("SfNativeShapes", self.shape_fields), ("SfNativeInputs", self.inputs), ("SfNativeWorkspaces", self.workspaces)):
            lines.append(f"typedef struct {{")
            if not fields:
                lines.append("    uint32_t reserved;")
            for field in fields:
                if name == "SfNativeWorkspaces":
                    lines.extend([
                        f"    {field.ctype} *{field.name};",
                        f"    uint32_t {field.name}_capacity;",
                        f"    uint32_t {field.name}_offset;",
                        f"    uint32_t {field.name}_count;",
                        f"    uint32_t {field.name}_elem_nbytes;",
                    ])
                elif name == "SfNativeShapes":
                    lines.append(f"    {field.ctype} {field.name};")
                else:
                    lines.append(f"    const {field.ctype} *{field.name};")
                    lines.append(f"    uint32_t {field.name}_numel;")
            lines.append(f"}} {name};")
            lines.append("")
        lines.extend([
            "typedef struct { uint32_t reserved; } SfNativeTarget;",
            "typedef struct { uint32_t reserved; } SfNativeResolved;",
            "typedef struct {",
            "    SfNativeShapes shapes;",
            "    SfNativeInputs inputs;",
            "    SfNativeTarget target;",
            "    SfNativeWorkspaces workspaces;",
            "    SfNativeResolved resolved;",
            "} SfNativeAbi;",
            "",
            "uintptr_t sf_native_abi_address(void);",
            "uintptr_t sf_native_storage_address(uint32_t offset);",
            "int32_t sf_native_guard_status(void);",
            "void sf_native_reset_guards(void);",
        ])
        for field in self.inputs:
            lines.append(f"uintptr_t sf_native_input_{field.name}_address(void);")
        for field in self.workspaces:
            lines.extend([
                f"uintptr_t sf_native_workspace_{field.name}_address(void);",
                f"uint32_t sf_native_workspace_{field.name}_offset(void);",
                f"uint32_t sf_native_workspace_{field.name}_count(void);",
            ])
        lines.extend(["#endif", ""])
        return "\n".join(lines)


def build_minimal(
    contract: NativeContract,
    source: str,
    root: Path,
    *,
    extra_cflags: Iterable[str] = (),
) -> Path:
    """@brief 在指定 worker 目录编译独立 native64 ABI 的最小闭环。"""
    root.mkdir(parents=True, exist_ok=True)
    header = root / "host_contract.h"
    implementation = root / "host.c"
    library = root / "host.dylib"
    header.write_text(contract.header(), encoding="utf-8")
    implementation.write_text(source, encoding="utf-8")
    done = subprocess.run(
        [
            "/usr/bin/clang", "-std=c99", "-O2", "-fPIC", "-shared", "-Wall", "-Wextra", "-Werror",
            *extra_cflags,
            str(implementation), "-o", str(library),
        ],
        cwd=root,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )
    if done.returncode != 0:
        raise HostProgramError(f"native ABI compilation failed: {done.stderr}")
    return library


__all__ = ["NativeContract", "NativeField", "build_minimal"]
