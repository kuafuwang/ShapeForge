"""The compilation contract (c, I, h) and the ABI template.

Paper correspondence (Section 3.1):
  c  -- fixed specialization: tensor dimensions and constexpr parameters. They are
        injected as ``constant constexpr`` declarations in the template header.
  I  -- runtime launch interface: threadgroups per grid, threads per threadgroup and
        the buffer argument ABI (index, name, access, scalar types).
  h  -- the target GPU. Here always the local Apple GPU (Apple9 family on M4).

A candidate kernel is *valid* only if it exposes exactly this ABI. The harness
(not the model) chooses the launch configuration.
"""
# 契约关。compile 把这里生成的文件头接到候选正文前面；abi 关再拿编译结果对这份契约。
# 契约固定函数名、每个参数的槽位与读写、以及并发度（grid 上有多少线程组、每组多少线程）。这些在 tasks 里由框架写成 Contract。模型提交的是带这个签名的内核函数，改不了这份对象。
# 模型改不了它：提示词里展示的是 describe() 和 abi_stub()，编译器看到的头来自 render_header()，对不上就在 abi 关失败。

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

from .dtypes import get_dtype

SIMD_WIDTH = 32  # Apple GPUs execute 32-wide SIMD groups, same as an NVIDIA warp.

HEADER_BEGIN = "// ---- BEGIN contract header (generated by the harness; do not redefine) ----"
HEADER_END = "// ---- END contract header ----"


@dataclass(frozen=True)
class AbiArg:
    """One kernel argument bound to a Metal buffer slot."""

    name: str
    index: int
    role: str  # "input" | "output" | "scalar"
    dtype: str  # key of tcenv.dtypes.DTYPES
    shape: tuple[int, ...] = ()  # buffers only
    value: int | float | None = None  # scalars only
    doc: str = ""

    def __post_init__(self) -> None:
        if self.role not in ("input", "output", "scalar"):
            raise ValueError(f"bad role {self.role!r}")
        if self.role == "scalar" and self.value is None:
            raise ValueError(f"scalar arg {self.name} needs a value")
        get_dtype(self.dtype)

    @property
    def numel(self) -> int:
        n = 1
        for s in self.shape:
            n *= int(s)
        return n

    @property
    def nbytes(self) -> int:
        d = get_dtype(self.dtype)
        return d.nbytes if self.role == "scalar" else self.numel * d.nbytes

    # 模型必须照这个签名写参数：输入只读、输出可写、标量是 constant。abi 关对的就是槽位、名字和这三种读写。
    @property
    def msl_declaration(self) -> str:
        msl = get_dtype(self.dtype).msl
        if self.role == "input":
            return f"device const {msl}* {self.name} [[buffer({self.index})]]"
        if self.role == "output":
            return f"device {msl}* {self.name} [[buffer({self.index})]]"
        return f"constant {msl}& {self.name} [[buffer({self.index})]]"


@dataclass(frozen=True)
class Contract:
    kernel_name: str
    grid: tuple[int, int, int]  # threadgroups per grid
    threads: tuple[int, int, int]  # threads per threadgroup
    args: tuple[AbiArg, ...]
    # (name, msl_type, value). Rendered as `constant constexpr <type> <name> = <value>;`
    constants: tuple[tuple[str, str, Any], ...] = ()
    gpu: str = "Apple M4 Max (Apple9 GPU family)"

    # -- derived -------------------------------------------------------------
    # 并发度由框架指定：grid 是线程组个数，threads 是每组线程数。模型不能在源码里另选一套启动配置。
    @property
    def threads_per_tg(self) -> int:
        return self.threads[0] * self.threads[1] * self.threads[2]

    @property
    def num_warps(self) -> int:
        return self.threads_per_tg // SIMD_WIDTH

    @property
    def num_threadgroups(self) -> int:
        return self.grid[0] * self.grid[1] * self.grid[2]

    @property
    def buffers(self) -> tuple[AbiArg, ...]:
        return tuple(a for a in self.args if a.role != "scalar")

    @property
    def inputs(self) -> tuple[AbiArg, ...]:
        return tuple(a for a in self.args if a.role == "input")

    @property
    def outputs(self) -> tuple[AbiArg, ...]:
        return tuple(a for a in self.args if a.role == "output")

    @property
    def scalars(self) -> tuple[AbiArg, ...]:
        return tuple(a for a in self.args if a.role == "scalar")

    def arg(self, name: str) -> AbiArg:
        for a in self.args:
            if a.name == name:
                return a
        raise KeyError(name)

    # -- rendering -------------------------------------------------------------
    # 头里的 constexpr 要写成 Metal 字面量：float 加 f，half / bfloat 不加；uint 加 u，ulong 加 ul。describe() 给模型看的是原来的值。
    @staticmethod
    def _fmt_const(msl_type: str, value: Any) -> str:
        if msl_type in ("float", "half", "bfloat"):
            return repr(float(value)) + ("f" if msl_type == "float" else "")
        if msl_type in ("uint", "ulong"):
            return f"{int(value)}u" if msl_type == "uint" else f"{int(value)}ul"
        return str(int(value))

    # 编译单元最前面的文件头：Metal 标准头、using，以及契约里每一条 constant constexpr。这一段不是模型写的。
    def render_header(self) -> str:
        lines = [HEADER_BEGIN, "#include <metal_stdlib>", "#include <metal_simdgroup>", "#include <metal_simdgroup_matrix>", "using namespace metal;"]
        for name, msl_type, value in self.constants:
            lines.append(f"constant constexpr {msl_type} {name} = {self._fmt_const(msl_type, value)};")
        lines.append(HEADER_END)
        return "\n".join(lines) + "\n"

    # 把头和候选正文接成编译器真正看到的那一份，并返回头占了多少行，供诊断行号映回模型自己的源码。
    def assemble(self, kernel_code: str) -> tuple[str, int]:
        """Return (full MSL source, number of header lines preceding the candidate's code)."""
        header = self.render_header()
        offset = header.count("\n")
        return header + kernel_code, offset

    # 给模型看的签名骨架。送去编译的是 assemble 接出来的全文。
    def abi_stub(self) -> str:
        """Kernel signature skeleton shown to the model."""
        decls = ",\n    ".join(a.msl_declaration for a in self.args)
        return (
            f"kernel void {self.kernel_name}(\n    {decls},\n"
            "    /* ...plus any [[thread_position_in_grid]]-style attribute parameters you want... */\n)"
        )

    # 写进提示词的契约正文。判卷用的仍是 tasks 里这份对象：函数名、并发度、编译期常量、每个 buffer 的槽位和读写。
    def describe(self) -> str:
        """Human/LLM readable summary of the whole contract."""
        out = [f"target gpu       : {self.gpu}", f"kernel name      : {self.kernel_name}"]
        out.append(f"threadgroups     : grid = {self.grid}  ({self.num_threadgroups} threadgroups, fixed by the harness)")
        out.append(f"threads / group  : {self.threads}  ({self.threads_per_tg} threads = {self.num_warps} SIMD groups of {SIMD_WIDTH}; fixed)")
        out.append("compile-time constants (already defined in the header):")
        for name, msl_type, value in self.constants:
            out.append(f"  constant constexpr {msl_type} {name} = {value}")
        out.append("buffer / scalar arguments (index, name and access are fixed):")
        for a in self.args:
            shape = f" shape={list(a.shape)}" if a.shape else ""
            val = f" value={a.value}" if a.role == "scalar" else ""
            out.append(f"  [[buffer({a.index})]] {a.role:6s} {a.dtype:5s} {a.name}{shape}{val}  {a.doc}".rstrip())
        return "\n".join(out)

    # 编译器的行号属于「头 + 正文」这一份。减掉头的行数，反馈才能指向模型写的 kernel.metal。
    def rewrite_compiler_lines(self, message: str, header_lines: int) -> str:
        """Map ``program_source:L:C`` locations back to the candidate's own line numbers."""

        def sub(m: re.Match) -> str:
            line = int(m.group(1)) - header_lines
            # 减完还不足 1，诊断落在框架生成的头里，行号改标成 <contract header>。
            return f"kernel.metal:{line}:{m.group(2)}" if line >= 1 else f"<contract header>:{m.group(1)}:{m.group(2)}"

        return re.sub(r"program_source:(\d+):(\d+)", sub, message)


@dataclass
class TaskMeta:
    """Light-weight, serialisable task identity (what workers need to reconstruct a task)."""

    name: str
    dtype: str
    size: str = "paper"
    extra: dict = field(default_factory=dict)
